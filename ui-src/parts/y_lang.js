const Lang={
  on:false, obs:null,
  apply(first){
    const en=S.lang==='en';
    if(en===this.on&&!first) return;
    if(!en){ if(this.on) location.reload(); return; }
    this.on=true;
    const r=document.documentElement;
    r.lang='en'; r.dir='ltr'; r.classList.add('lang-en');
    S.ar=false;
    this.walk(document.body);
    this.watch();
  },
  tr(t){
    const k=t.trim(); if(!k||k.length>80) return null;
    if(LANG_EN[k]) return t.replace(k,LANG_EN[k]);
    const dash=k.match(/^(.+?)\s*[—–-]\s*(.+)$/);
    if(dash&&LANG_EN[dash[1].trim()]) return t.replace(k,LANG_EN[dash[1].trim()]+' — '+(LANG_EN[dash[2].trim()]||dash[2].trim()));
    const par=k.match(/^(.+?)\s*\(([^)]*)\)$/);
    if(par&&LANG_EN[par[1].trim()]) return t.replace(k,LANG_EN[par[1].trim()]+' ('+par[2]+')');
    return null;
  },
  walk(root){
    if(!root) return;
    const it=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
    const jobs=[];
    while(it.nextNode()){ const n=it.currentNode; if(!/[؀-ۿ]/.test(n.nodeValue)) continue; const v=this.tr(n.nodeValue); if(v) jobs.push([n,v]); }
    jobs.forEach(([n,v])=>n.nodeValue=v);
    const els=root.nodeType===1?[root,...root.querySelectorAll('[placeholder],[title],[aria-label]')]:[];
    for(const el of els){
      for(const a of ['placeholder','title','aria-label']){
        const v=el.getAttribute&&el.getAttribute(a); if(!v||!/[؀-ۿ]/.test(v)) continue;
        const t=this.tr(v); if(t) el.setAttribute(a,t);
      }
    }
  },
  watch(){
    if(this.obs) return;
    let queue=[], t=0;
    this.obs=new MutationObserver(ms=>{
      for(const m of ms){ m.addedNodes.forEach(n=>queue.push(n)); if(m.type==='characterData') queue.push(m.target); }
      clearTimeout(t); t=setTimeout(()=>{ const q=queue; queue=[]; q.forEach(n=>this.walk(n.nodeType===3?n.parentNode:n)); },60);
    });
    this.obs.observe(document.body,{childList:true,subtree:true,characterData:true});
  }
};
